#!/bin/sh
# Drama 3 compact NVFP4 (#4144) and semantic CFG (#4153) merged, on TOP's Spark through the Desk's GPU door (not for merge):
#   swarm gpu-run plotarmordev/TensorFold SHA docs/recipes/drama3-cuda/combined-gb10.sh
# #4144's whole GB10 check (tools/zig/drama3_compact_gb10.sh), then #4153's CFG guidance check. The door's checkout is
# shallow and offline, so the check's pre-feature tree (main merged with #4153, no compact router) is rebuilt from
# combined-base.patch and must match its tree hash. The Desk's checkpoint copy is checked against the published manifest.
set -eu
pilot=/assets/drama3-pilot
fp8=$pilot/checkpoint
compact=$pilot/drama-3-NVFP4-Pruned
staged=$pilot/cuda-build-toolchain
zig=zig-aarch64-linux-0.17.0
gcc=arm-gnu-toolchain-14.3.rel1-aarch64-aarch64-none-linux-gnu
nvcc=/usr/local/cuda/bin/nvcc
out=/work/out/drama3-combined
here=docs/recipes/drama3-cuda
export GIT_CONFIG_COUNT=1 GIT_CONFIG_KEY_0=safe.directory GIT_CONFIG_VALUE_0='*'
(cd "$compact" && echo 'f447d4ba6cbb79ddadbd4148ec3b8eb6b5ea8bf54a13d24f552f93474b0dd07d  MANIFEST.sha256' | sha256sum -c &&
    echo "manifest: $(sha256sum -c MANIFEST.sha256 | grep -c ': OK$') OK")
export GIT_INDEX_FILE=/work/base.index
git read-tree HEAD
git rm -q --cached "$here/combined-gb10.sh" "$here/combined-base.patch"
git apply --cached "$here/combined-base.patch"
tree=$(git write-tree)
unset GIT_INDEX_FILE
[ "$tree" = c5d6fe9064bb7050a8f85432c7b6e799e4335d98 ] || { echo "the patch gave tree $tree, not main 37fa51d2 + #4153 f2c1c032" >&2; exit 2; }
base=$(echo "main 37fa51d2 merged with #4153 f2c1c032, rebuilt" | git -c user.name=desk -c user.email=desk@localhost commit-tree "$tree")
echo "commit $(git rev-parse HEAD) pre-feature $base (tree $tree)"
tar -C /work -xJf "$staged/$zig.tar.xz"
tar -C /work -xJf "$staged/$gcc.tar.xz"
export PATH=/work/$zig:$PATH ZIG_GLOBAL_CACHE_DIR=/work/zig-cache ZIG_LOCAL_CACHE_DIR=/work/zig-cache
export LD_LIBRARY_PATH=/usr/local/cuda/targets/sbsa-linux/lib${LD_LIBRARY_PATH:+:$LD_LIBRARY_PATH}
export NVCC_PREPEND_FLAGS="-ccbin /work/$gcc/bin/aarch64-none-linux-gnu-g++"
status=0
tools/zig/drama3_compact_gb10.sh "$base" "$fp8" "$compact" "$fp8/codec.pth" "$nvcc" "$out/compact" || status=$?
echo "drama3_compact_gb10.sh exit $status"
if [ "$status" -ne 0 ]; then
    for f in "$out"/compact/*.log; do echo "== $f"; tail -n 4 "$f"; done
    exit "$status"
fi
grep -q 'routed experts held 7369 of 10240;' "$out/compact/RECEIPT.txt"
# guidance acts only on a reference-backed voice: a few seconds of Drama 3's own voice, as in drama3-pruned-main
zig build drama3-generate drama3-voice -Dsm=121 -Dnvcc=$nvcc -Doptimize=ReleaseFast --prefix /work/sm121
zig build -Dgpu=spark -Dnvcc=$nvcc --prefix /work/sm121
bin=/work/sm121/bin
text="The lighthouse keeper climbed the winding stairs and lit the lamp before the storm."
mkdir -p "$out/voices"
"$bin/drama3-generate" --model "$fp8" --codec "$fp8/codec.pth" --text "$text" --wav "$out/synthetic.wav" 2>"$out/synthetic.log"
"$bin/drama3-voice" --codec "$fp8/codec.pth" --ref-audio "$out/synthetic.wav" --ref-text "$text" \
    --source-kind synthetic --source-note "Drama 3's built-in voice, generated by drama3-generate." \
    --out "$out/voices/synthetic.json" --generate "$bin/drama3-generate"
(cd tools/zig && python3 drama_guidance_check.py --bin /work/sm121/native/bin/tensorfold-native --checkpoint "$fp8" \
    --voices "$out/voices" --voice synthetic --out "$out/guidance")
echo "CHECK guidance PASS"
