#!/bin/sh
# Desk door wrapper (scratch branch, not for merge): contract, FP8 and NVFP4 guidance, CFG-off main against head.
set -u
pilot=/assets/drama3-pilot
fp8=$pilot/checkpoint
staged=$pilot/cuda-build-toolchain
gcc=arm-gnu-toolchain-14.3.rel1-aarch64-aarch64-none-linux-gnu
main_sha=1587c8caee631dcc97c8fbb68f4bba353353c4c5
out=/work/out/drama3-cfg
tar -C /work -xJf "$staged/zig-aarch64-linux-0.17.0.tar.xz"
tar -C /work -xJf "$staged/$gcc.tar.xz"
export PATH=/work/zig-aarch64-linux-0.17.0:/usr/local/cuda/bin:$PATH ZIG_GLOBAL_CACHE_DIR=/work/zig-cache ZIG_LOCAL_CACHE_DIR=/work/zig-cache
export LD_LIBRARY_PATH=/usr/local/cuda/targets/sbsa-linux/lib${LD_LIBRARY_PATH:+:$LD_LIBRARY_PATH}
export NVCC_PREPEND_FLAGS="-ccbin /work/$gcc/bin/aarch64-none-linux-gnu-g++"
export GIT_CONFIG_COUNT=1 GIT_CONFIG_KEY_0=safe.directory GIT_CONFIG_VALUE_0='*'
echo "== assets"; ls "$pilot"; cat "$pilot/MANIFEST" 2>/dev/null | head -40
nvfp4=$(ls -d "$pilot"/*/ 2>/dev/null | grep -iE 'nvfp4|prun' | grep -v 5900 | head -1); nvfp4=${nvfp4%/}
echo "fp8=$fp8 nvfp4=$nvfp4"
for m in fp8 nvfp4; do eval d=\$$m; [ -n "$d" ] && sha256sum "$d/config.json" | sed "s/^/$m config.json sha256 /"; cat "$d/REVISION" "$d/.revision" 2>/dev/null | sed "s/^/$m revision /"; done
for r in fishaudio/drama-3 plotarmordev/drama-3-NVFP4-Pruned; do
    curl -s -m 20 "https://huggingface.co/api/models/$r" | python3 -c "import json,sys; d=json.load(sys.stdin); print('hf', '$r', d.get('sha'))" 2>&1
done

sh docs/recipes/drama3-cuda/cfg-mix-gb10.sh > /work/contract.log 2>&1
contract=$?
echo "== contract (exit $contract)"; grep -E "CONTROL|FAIL|SUMMARY|commit|release" /work/contract.log

set -e
zig build drama3-generate drama3-voice -Dsm=121 -Dnvcc=/usr/local/cuda/bin/nvcc -Doptimize=ReleaseFast --prefix zig-out/sm121
git worktree add -f /work/main "$main_sha"
(cd /work/main && zig build install fatbins -Dsm=121 -Dnvcc=/usr/local/cuda/bin/nvcc -Doptimize=ReleaseFast --prefix zig-out/sm121 \
    && zig build drama3-generate -Dsm=121 -Dnvcc=/usr/local/cuda/bin/nvcc -Doptimize=ReleaseFast --prefix zig-out/sm121 \
    && zig build -Dgpu=spark -Dnvcc=/usr/local/cuda/bin/nvcc --prefix zig-out/sm121)
bin=zig-out/sm121/bin
text="The lighthouse keeper climbed the winding stairs and lit the lamp before the storm."
mkdir -p "$out/voices"
"$bin/drama3-generate" --model "$fp8" --codec "$fp8/codec.pth" --text "$text" --wav "$out/synthetic.wav" 2>"$out/synthetic.log"
"$bin/drama3-voice" --codec "$fp8/codec.pth" --ref-audio "$out/synthetic.wav" --ref-text "$text" \
    --source-kind synthetic --source-note "Drama 3's built-in voice, generated by drama3-generate." \
    --out "$out/voices/synthetic.json" --generate "$bin/drama3-generate"
set +e

guide() {  # checkpoint name, dir
    (cd tools/zig && python3 drama_guidance_check.py --bin ../../zig-out/sm121/native/bin/tensorfold-native \
        --checkpoint "$2" --voices "$out/voices" --voice synthetic --out "$out/guidance-$1")
    echo "guidance $1 exit $?"
    python3 - "$1" "$out/guidance-$1/results.json" <<'PY'
import json, sys
r = json.load(open(sys.argv[2]))
print(f"{sys.argv[1]} pass={r['pass']} problems={len(r['problems'])}")
for rows, modes in r["runs"].items():
    for mode, run in modes.items():
        print(f"{sys.argv[1]} rows={rows} {mode} cache_hits={run['cache_hits']}")
        for name, rep in run["replies"].items():
            print(f"PCM {sys.argv[1]} rows={rows} {mode} {name} {rep['sha256']} bytes={rep['bytes']} total_s={rep['total_s']:.3f}")
PY
}
guide fp8 "$fp8"
fp8_guidance=$?
nvfp4_guidance=1
[ -n "$nvfp4" ] && { guide nvfp4 "$nvfp4"; nvfp4_guidance=$?; }

echo "== CFG off, main $main_sha against head $(git rev-parse HEAD), FP8"
for tree in main head; do
    root=.; [ $tree = main ] && root=/work/main
    "$root/$bin/drama3-generate" --model "$fp8" --text "$text" --seed 7 --out "$out/$tree.frames" 2>"$out/$tree-generate.log"
    sha256sum "$out/$tree.frames" | sed "s/^/tokens $tree /"; tail -n 1 "$out/$tree-generate.log" | sed "s/^/$tree /"
done
cmp "$out/main.frames" "$out/head.frames" && echo "tokens main = head" || echo "TOKENS DIFFER"
python3 - "$out" "$fp8" /work/main/zig-out/sm121/native/bin/tensorfold-native zig-out/sm121/native/bin/tensorfold-native <<'PY'
import os, sys, types
from pathlib import Path
sys.path.insert(0, "tools/zig")
from drama_reference_cache_check import TEXTS, serve
out, ckpt, bins = Path(sys.argv[1]), sys.argv[2], {"main": sys.argv[3], "head": sys.argv[4]}
steps = [(f"t{i}", "synthetic", t) for i, t in enumerate(TEXTS[:3])]
steps = [*steps, [("lane-a", "synthetic", TEXTS[3]), ("lane-b", "synthetic", TEXTS[4])]]
replies = {}
for tree, b in bins.items():
    args = types.SimpleNamespace(bin=b, checkpoint=ckpt, voices=out / "voices", ready_timeout=900, timeout=300)
    replies[tree] = serve(args, dict(os.environ), [], out / f"cfg-off-{tree}.log", steps)
for name in replies["head"]:
    m, h = replies["main"][name], replies["head"][name]
    print(f"cfg-off {name} main {m['sha256']} {m['total_s']:.3f}s head {h['sha256']} {h['total_s']:.3f}s",
          "equal" if m["sha256"] == h["sha256"] else "DIFFER")
PY
cfg_off=$?
echo "contract $contract; guidance fp8 $fp8_guidance nvfp4 $nvfp4_guidance; cfg-off $cfg_off"
[ "$contract" -eq 0 ] && [ "$fp8_guidance" -eq 0 ] && [ "$nvfp4_guidance" -eq 0 ] && [ "$cfg_off" -eq 0 ]
